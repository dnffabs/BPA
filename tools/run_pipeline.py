#!/usr/bin/env python3
"""Run all prerequisite stages; never reuse facts from a different binary."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time

from generate_facts import generate
from memory_model import build, read_rows, write_rows

ROOT = Path(__file__).resolve().parents[1]
STAGES = ("preprocess", "cfg", "ssa", "boundary_gen", "analysis", "compare")


def find_souffle():
    configured = os.environ.get("SOUFFLE")
    if configured:
        result = shutil.which(configured)
        if not result:
            raise ValueError(f"SOUFFLE executable not found: {configured}")
        return result
    result = shutil.which("souffle")
    if result:
        return result
    workspace = ROOT.parents[1] / "souffle"
    if workspace.is_file():
        return str(workspace)
    raise ValueError("Souffle not found; set SOUFFLE=/path/to/souffle")


def datalog(facts, name, souffle, jobs, log):
    command = [souffle, "-w", "-j", str(jobs), "-F", str(facts), "-D", str(facts), str(ROOT / "rules" / name)]
    p = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    log.write_text(p.stdout)
    if p.returncode:
        raise RuntimeError(f"{name} failed (exit {p.returncode}); {log}\n{p.stdout}")


def run(args):
    binary = Path(args.binary).resolve(strict=True)
    digest = hashlib.sha256(binary.read_bytes()).hexdigest()
    identity = hashlib.sha256(str(binary).encode()).hexdigest()[:8]
    base = Path(args.output).resolve() if args.output else ROOT / "build" / f"{binary.name}_{identity}_dir"
    base.mkdir(parents=True, exist_ok=True)
    facts = base / "facts"
    souffle = find_souffle()
    summary = {"binary": str(binary), "binary_sha256": digest, "status": "running", "stages": {},
               "python": sys.version.split()[0], "schema": 2, "facts": str(facts)}
    with (base / ".lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        # This subdirectory is generated by this driver, and only it is reset.
        if facts.is_symlink():
            raise ValueError(f"Refusing to replace symlink facts directory: {facts}")
        if facts.exists():
            shutil.rmtree(facts)
        facts.mkdir()
        (base / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
        try:
            stop = args.stage or ("compare" if args.compare else "analysis")
            for stage in STAGES[:STAGES.index(stop) + 1]:
                start = time.monotonic()
                print(f"[{stage}] {binary.name}", flush=True)
                if stage == "preprocess":
                    generate(binary, facts, args.entry)
                    datalog(facts, "preprocess.dl", souffle, args.jobs, base / "preprocess.log")
                elif stage == "cfg":
                    datalog(facts, "cfg.dl", souffle, args.jobs, base / "cfg.log")
                elif stage == "ssa":
                    datalog(facts, "ssa.dl", souffle, args.jobs, base / "ssa.log")
                elif stage == "boundary_gen":
                    summary["memory"] = build(facts)
                    for rule in ("stack_boundary.dl", "global_boundary.dl", "heap_boundary.dl", "aloc_gen.dl"):
                        datalog(facts, rule, souffle, args.jobs, base / f"{rule}.log")
                elif stage == "analysis":
                    datalog(facts, "analysis.dl", souffle, args.jobs, base / "analysis.log")
                    # CFG updates and actual/formal/return propagation are
                    # mutually recursive inside analysis.dl, not shell passes.
                    reached = {r[0] for r in read_rows(facts, "reachable_func")}
                    calls = [r for r in read_rows(facts, "call") if r[1] in reached and r[-1] == "1"]
                    summary["indirect_calls"] = len(calls)
                    summary["target_edges"] = len(read_rows(facts, "indirect_call_target"))
                    summary["external_target_edges"] = len(read_rows(facts, "external_call_target"))
                    summary["unresolved_calls"] = read_rows(facts, "unresolved_call")
                    summary["uncertain_calls"] = read_rows(facts, "uncertain_call")
                    summary["unsupported"] = [r for r in read_rows(facts, "unsupported") if r[0] in reached]
                    # Retain all sites in the denominator, even empty results.
                    by_site = {}
                    for site, target in read_rows(facts, "indirect_call_target"):
                        by_site.setdefault(site, []).append(target)
                    external_by_site = {}
                    for site, target in read_rows(facts, "external_call_target"):
                        external_by_site.setdefault(site, []).append(target)
                    write_rows(facts, "call_resolution", ((r[3], r[1], len(by_site.get(r[3], [])),
                        len(external_by_site.get(r[3], []))) for r in calls))
                elif stage == "compare":
                    result = subprocess.run([sys.executable, str(ROOT / "compare/evaluate.py"), str(binary),
                        str(facts / "stack_boundary.facts"), str(facts / "global_boundary.facts"),
                        "--output-dir", str(base / "evaluation")], text=True,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
                    (base / "compare.log").write_text(result.stdout)
                    if result.returncode:
                        raise RuntimeError(f"Comparison failed: {base / 'compare.log'}")
                summary["stages"][stage] = round(time.monotonic()-start, 4)
            summary["status"] = "completed"
        except Exception as error:
            summary["status"] = "failed"
            summary["error"] = str(error)
            raise
        finally:
            (base / "summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n")
    print(f"[done] {facts}")
    if "indirect_calls" in summary:
        print(f"[targets] sites={summary['indirect_calls']} edges={summary['target_edges']} unresolved={len(summary['unresolved_calls'])}")
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary")
    parser.add_argument("--output", "-o")
    parser.add_argument("--entry", default="main")
    parser.add_argument("--jobs", "-j", type=int, default=4)
    parser.add_argument("--compare", action="store_true", help="also evaluate boundaries using DWARF")
    parser.add_argument("--stage", choices=STAGES, help="run prerequisites through this stage")
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    try:
        run(args)
    except (ValueError, RuntimeError, OSError) as error:
        print(f"[error] {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
